import type { PaperStyleDef } from "./types";

function ruled(
  id: string,
  name: string,
  description: string,
  opts: {
    bg: string;
    spacing: number;
    color: string;
    margin?: PaperStyleDef["margin"];
    texture?: PaperStyleDef["texture"];
    category?: PaperStyleDef["category"];
    thickness?: number;
  },
): PaperStyleDef {
  return {
    id,
    name,
    category: opts.category || "ruled",
    description,
    bg: opts.bg,
    pattern: {
      kind: "ruled",
      spacing: opts.spacing,
      color: opts.color,
      thickness: opts.thickness ?? 1,
      startOffset: 48,
    },
    margin: opts.margin,
    texture: opts.texture || "none",
    dark: false,
    printable: true,
  };
}

