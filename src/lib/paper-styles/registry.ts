export const PAPER_STYLE_IDS = PAPER_STYLES.map((p) => p.id);

export function getPaperStyle(id?: string | null): PaperStyleDef | undefined {
  if (!id) return undefined;
  return PAPER_STYLES.find((p) => p.id === id);
}

export function resolvePaperStyle(id?: string | null): PaperStyleDef | null {
  if (!id) return null;
  return getPaperStyle(id) ?? null;
}

